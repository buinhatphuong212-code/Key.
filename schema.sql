-- RED KEY STORE schema for Supabase PostgreSQL.
-- Run in Supabase SQL Editor. Review before production deployment.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  balance_vnd bigint not null default 0 check (balance_vnd >= 0),
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  price_vnd bigint not null check (price_vnd > 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.inventory_keys (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id),
  key_value text not null,
  sold_to uuid references auth.users(id),
  sold_at timestamptz,
  order_id bigint,
  created_at timestamptz not null default now()
);
create unique index if not exists inventory_key_value_unique on public.inventory_keys(key_value);
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id),
  product_id bigint not null references public.products(id),
  product_name text not null,
  price_vnd bigint not null check (price_vnd > 0),
  status text not null default 'completed' check (status in ('completed','refunded')),
  created_at timestamptz not null default now(),
  delivered_at timestamptz
);
alter table public.inventory_keys drop constraint if exists inventory_keys_order_id_fkey;
alter table public.inventory_keys add constraint inventory_keys_order_id_fkey foreign key(order_id) references public.orders(id);
create table if not exists public.deposits (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id),
  amount_vnd bigint not null check (amount_vnd between 10000 and 5000000),
  reference text not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  reviewed_by uuid references auth.users(id),
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);
create table if not exists public.wallet_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id),
  entry_type text not null check (entry_type in ('deposit','purchase','refund','adjustment')),
  amount_vnd bigint not null check (amount_vnd <> 0),
  note text not null default '',
  related_id bigint,
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path=public as $$
begin
 insert into public.profiles(id,display_name) values(new.id,coalesce(new.raw_user_meta_data->>'display_name','')) on conflict(id) do nothing;
 return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

create or replace function public.is_store_admin() returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.profiles where id=auth.uid() and is_admin=true);
$$;

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.inventory_keys enable row level security;
alter table public.orders enable row level security;
alter table public.deposits enable row level security;
alter table public.wallet_ledger enable row level security;

drop policy if exists "profile own read" on public.profiles;
create policy "profile own read" on public.profiles for select to authenticated using(id=auth.uid() or public.is_store_admin());
drop policy if exists "active products public read" on public.products;
create policy "active products public read" on public.products for select to anon,authenticated using(active=true or public.is_store_admin());
drop policy if exists "orders own read" on public.orders;
create policy "orders own read" on public.orders for select to authenticated using(user_id=auth.uid() or public.is_store_admin());
drop policy if exists "deposits own read" on public.deposits;
create policy "deposits own read" on public.deposits for select to authenticated using(user_id=auth.uid() or public.is_store_admin());
drop policy if exists "ledger own read" on public.wallet_ledger;
create policy "ledger own read" on public.wallet_ledger for select to authenticated using(user_id=auth.uid() or public.is_store_admin());
-- Deliberately no client policies for inventory_keys and no client write policies for money tables.

grant select on public.products to anon, authenticated;
grant select on public.profiles, public.orders, public.deposits, public.wallet_ledger to authenticated;
revoke all on public.inventory_keys from anon, authenticated;

create or replace function public.request_deposit(p_amount_vnd bigint,p_reference text) returns bigint language plpgsql security definer set search_path=public as $$
declare v_id bigint;
begin
 if auth.uid() is null then raise exception 'Bạn cần đăng nhập'; end if;
 if p_amount_vnd < 10000 or p_amount_vnd > 5000000 then raise exception 'Số tiền không hợp lệ'; end if;
 if length(trim(p_reference)) < 4 or length(p_reference) > 100 then raise exception 'Mã giao dịch không hợp lệ'; end if;
 insert into public.deposits(user_id,amount_vnd,reference) values(auth.uid(),p_amount_vnd,trim(p_reference)) returning id into v_id;
 return v_id;
end; $$;

create or replace function public.buy_product(p_product_id bigint) returns jsonb language plpgsql security definer set search_path=public as $$
declare v_user uuid:=auth.uid(); v_product public.products%rowtype; v_key public.inventory_keys%rowtype; v_order bigint;
begin
 if v_user is null then raise exception 'Bạn cần đăng nhập'; end if;
 select * into v_product from public.products where id=p_product_id and active=true for share;
 if not found then raise exception 'Sản phẩm không tồn tại hoặc đã ngừng bán'; end if;
 perform 1 from public.profiles where id=v_user for update;
 if (select balance_vnd from public.profiles where id=v_user) < v_product.price_vnd then raise exception 'Số dư không đủ'; end if;
 select * into v_key from public.inventory_keys where product_id=p_product_id and sold_to is null order by id limit 1 for update skip locked;
 if not found then raise exception 'Sản phẩm đã hết key'; end if;
 update public.profiles set balance_vnd=balance_vnd-v_product.price_vnd where id=v_user;
 insert into public.orders(user_id,product_id,product_name,price_vnd,status,delivered_at) values(v_user,p_product_id,v_product.name,v_product.price_vnd,'completed',now()) returning id into v_order;
 update public.inventory_keys set sold_to=v_user,sold_at=now(),order_id=v_order where id=v_key.id;
 insert into public.wallet_ledger(user_id,entry_type,amount_vnd,note,related_id) values(v_user,'purchase',-v_product.price_vnd,'Mua: '||v_product.name,v_order);
 return jsonb_build_object('order_id',v_order,'key_value',v_key.key_value,'product_name',v_product.name);
end; $$;

create or replace function public.admin_pending_deposits() returns table(id bigint,email text,amount_vnd bigint,reference text,created_at timestamptz) language plpgsql security definer set search_path=public as $$
begin
 if not public.is_store_admin() then raise exception 'Không có quyền admin'; end if;
 return query select d.id,u.email::text,d.amount_vnd,d.reference,d.created_at from public.deposits d join auth.users u on u.id=d.user_id where d.status='pending' order by d.created_at;
end; $$;

create or replace function public.admin_review_deposit(p_deposit_id bigint,p_approve boolean) returns void language plpgsql security definer set search_path=public as $$
declare d public.deposits%rowtype;
begin
 if not public.is_store_admin() then raise exception 'Không có quyền admin'; end if;
 select * into d from public.deposits where id=p_deposit_id for update;
 if not found or d.status<>'pending' then raise exception 'Yêu cầu không tồn tại hoặc đã xử lý'; end if;
 update public.deposits set status=case when p_approve then 'approved' else 'rejected' end,reviewed_by=auth.uid(),reviewed_at=now() where id=d.id;
 if p_approve then
   update public.profiles set balance_vnd=balance_vnd+d.amount_vnd where id=d.user_id;
   insert into public.wallet_ledger(user_id,entry_type,amount_vnd,note,related_id) values(d.user_id,'deposit',d.amount_vnd,'Nạp tiền đã đối soát',d.id);
 end if;
end; $$;

create or replace function public.admin_create_product(p_name text,p_description text,p_price_vnd bigint) returns bigint language plpgsql security definer set search_path=public as $$
declare v_id bigint;
begin
 if not public.is_store_admin() then raise exception 'Không có quyền admin'; end if;
 if length(trim(p_name))<2 or p_price_vnd<1000 then raise exception 'Thông tin sản phẩm không hợp lệ'; end if;
 insert into public.products(name,description,price_vnd) values(trim(p_name),coalesce(p_description,''),p_price_vnd) returning id into v_id;
 return v_id;
end; $$;

create or replace function public.admin_add_key(p_product_id bigint,p_key_value text) returns bigint language plpgsql security definer set search_path=public as $$
declare v_id bigint;
begin
 if not public.is_store_admin() then raise exception 'Không có quyền admin'; end if;
 if length(trim(p_key_value))<4 then raise exception 'Key không hợp lệ'; end if;
 insert into public.inventory_keys(product_id,key_value) values(p_product_id,trim(p_key_value)) returning id into v_id;
 return v_id;
end; $$;

revoke all on function public.request_deposit(bigint,text) from public;
revoke all on function public.buy_product(bigint) from public;
revoke all on function public.admin_pending_deposits() from public;
revoke all on function public.admin_review_deposit(bigint,boolean) from public;
revoke all on function public.admin_create_product(text,text,bigint) from public;
revoke all on function public.admin_add_key(bigint,text) from public;
grant execute on function public.request_deposit(bigint,text) to authenticated;
grant execute on function public.buy_product(bigint) to authenticated;
grant execute on function public.admin_pending_deposits() to authenticated;
grant execute on function public.admin_review_deposit(bigint,boolean) to authenticated;
grant execute on function public.admin_create_product(text,text,bigint) to authenticated;
grant execute on function public.admin_add_key(bigint,text) to authenticated;

